"""
Build a demo database: prod's table structure, filled with made-up data.

For sharing the app with someone who must not see live data or the prod login.
The demo deployment is a second app service pointed at this database, with its
own APP_USERNAME / APP_PASSWORD (see auth.py) and no SALARY_API_* vars.

    python scripts/setup_test_db.py --target mysql://user:pass@host:port/visma_test
    python scripts/setup_test_db.py --target ... --source mysql://...prod.../visma_financial
    python scripts/setup_test_db.py --target ... --reset     # wipe and re-seed

The source (default: the .env DB) is only read - SHOW CREATE TABLE/VIEW, never a
row. Tables the app creates and migrates itself (projects and their ledgers,
bill allocations, sales invoices, vendor aliases) are then rebuilt from the
app's own DDL, so a source that lags behind the code can't hand the demo a
stale shape. The data is generated by scripts/demo_seed.py; nothing real is
copied.

Refuses to write to a target that is the source, or that already holds rows
(unless --reset, which drops and recreates every table).
"""

import argparse
import os
import re
import sys
from urllib.parse import urlparse, unquote

import mysql.connector

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))
from config import Config  # noqa: E402
from database import DatabaseManager  # noqa: E402
import demo_seed  # noqa: E402

# Owned by DatabaseManager.ensure_* - dropped after the clone and recreated
# from the code's DDL.
APP_OWNED_TABLES = [
    'project_po_variations', 'project_po_actuals', 'project_cash_payments',
    'project_third_party_payments', 'project_pos', 'projects',
    'bill_project_allocations', 'sales_line_items', 'sales_invoices',
    'vendor_aliases', 'vendor_alias_splits',
]


def parse_url(url):
    u = urlparse(url)
    if u.scheme not in ('mysql', 'mysql+pymysql'):
        sys.exit(f"Not a mysql:// URL: {url.split('@')[-1]}")
    return {'host': u.hostname, 'port': u.port or 3306,
            'user': unquote(u.username or ''), 'password': unquote(u.password or ''),
            'database': (u.path or '/').lstrip('/')}


def env_source():
    return {'host': Config.DB_HOST, 'port': Config.DB_PORT, 'user': Config.DB_USER,
            'password': Config.DB_PASSWORD, 'database': Config.DB_DATABASE}


def connect(cfg, with_db=True):
    kw = {k: cfg[k] for k in ('host', 'port', 'user', 'password')}
    if with_db:
        kw['database'] = cfg['database']
    return mysql.connector.connect(**kw)


def read_schema(src):
    """[(name, 'BASE TABLE'|'VIEW', create_sql)] from the source, tables first."""
    conn = connect(src)
    cur = conn.cursor()
    cur.execute("SELECT TABLE_NAME, TABLE_TYPE FROM information_schema.TABLES "
                "WHERE TABLE_SCHEMA=%s ORDER BY TABLE_TYPE, TABLE_NAME",
                (src['database'],))
    out = []
    for name, typ in cur.fetchall():
        kind = 'VIEW' if typ == 'VIEW' else 'TABLE'
        cur.execute(f"SHOW CREATE {kind} `{name}`")
        sql = cur.fetchone()[1]
        sql = re.sub(r'\s+AUTO_INCREMENT=\d+', '', sql)
        sql = re.sub(r'DEFINER=`[^`]*`@`[^`]*`\s*', '', sql)
        out.append((name, typ, sql))
    conn.close()
    return out


def apply_schema(tgt, schema, reset):
    conn = connect(tgt, with_db=False)
    cur = conn.cursor()
    cur.execute(f"CREATE DATABASE IF NOT EXISTS `{tgt['database']}` "
                "CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci")
    cur.execute(f"USE `{tgt['database']}`")

    cur.execute("SELECT TABLE_NAME, TABLE_TYPE FROM information_schema.TABLES "
                "WHERE TABLE_SCHEMA=%s", (tgt['database'],))
    existing = dict(cur.fetchall())
    populated = []
    for name, typ in existing.items():
        if typ == 'BASE TABLE':
            cur.execute(f"SELECT EXISTS(SELECT 1 FROM `{name}`)")
            if cur.fetchone()[0]:
                populated.append(name)
    if populated and not reset:
        sys.exit(f"Target already holds rows in {', '.join(sorted(populated))}. "
                 "Re-run with --reset to wipe and re-seed it.")

    cur.execute("SET FOREIGN_KEY_CHECKS=0")
    for name, typ in existing.items():
        cur.execute(f"DROP {'VIEW' if typ == 'VIEW' else 'TABLE'} IF EXISTS `{name}`")
    for name, typ, sql in schema:
        if name in APP_OWNED_TABLES:
            continue
        try:
            cur.execute(sql)
            print(f"  created {'view ' if typ == 'VIEW' else ''}{name}")
        except mysql.connector.Error as e:
            # Some legacy views reference columns long since dropped; prod
            # carries them broken too, and nothing reads them.
            if typ != 'VIEW':
                raise
            print(f"  skipped view {name}: {e.msg}")
    cur.execute("SET FOREIGN_KEY_CHECKS=1")
    conn.commit()
    conn.close()


def apply_app_ddl(tgt):
    """Create/migrate the app-owned tables exactly as app startup would."""
    class TargetConfig:
        HOST, PORT, USER, PASSWORD, DATABASE = (tgt['host'], tgt['port'], tgt['user'],
                                                tgt['password'], tgt['database'])
    db = DatabaseManager(TargetConfig)
    steps = [db.ensure_projects_table, db.ensure_bill_allocations_table,
             db.ensure_vendor_alias_tables, db.ensure_sales_tables,
             db.ensure_validation_columns, db.ensure_category_source_columns]
    for step in steps:
        if step() is False:
            sys.exit(f"{step.__name__} failed on the target - see the message above.")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--target', required=True, help='mysql://user:pass@host:port/dbname')
    ap.add_argument('--source', help='mysql:// URL to read the schema from (default: .env DB)')
    ap.add_argument('--reset', action='store_true', help='drop existing tables in the target first')
    args = ap.parse_args()

    src = parse_url(args.source) if args.source else env_source()
    tgt = parse_url(args.target)
    if not tgt['database']:
        sys.exit("Target URL needs a database name, e.g. .../visma_test")
    if (src['host'], src['port'], src['database']) == (tgt['host'], tgt['port'], tgt['database']):
        sys.exit("Target is the source database - refusing.")

    print(f"Schema from {src['host']}:{src['port']}/{src['database']} (read only)")
    schema = read_schema(src)
    print(f"Building {tgt['host']}:{tgt['port']}/{tgt['database']}")
    apply_schema(tgt, schema, args.reset)
    apply_app_ddl(tgt)

    conn = connect(tgt)
    stats = demo_seed.seed(conn)
    conn.close()
    print("  seeded " + ", ".join(f"{v} {k.replace('_', ' ')}" for k, v in stats.items()))
    print("Done.")


if __name__ == '__main__':
    main()
